# Where each tree picture stands on its plot. The pictures are never changed: this measures the ground footprint
# (the widest spread near the bottom: roots, grass, fallen leaves, mushrooms, as a 2:1 disc) and writes app/scene/treeFit.ts with
# the footprint centre and one uniform scale that keeps the footprint inside the plot's soil.
# usage: python3 -I scripts/fit-trees.py
import glob, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HW, HH = 172, 86  # the plot diamond in 512 art pixels (fallen bits may touch the rim)

def footprint(a):
    # the ground disc seen at 2:1: as deep as half its width, ending at the picture's lowest pixel
    ys, xs = np.nonzero(a > 128)
    bottom = ys.max()
    m = ys > bottom - 40
    x0, x1 = xs[m].min(), xs[m].max()
    rx = (x1 - x0) / 2
    return (x0 + x1) / 2, bottom - rx / 2, rx, rx / 2

rows = []
for f in sorted(glob.glob(os.path.join(ROOT, 'public/assets/trees/tree_*.png'))):
    a = np.array(Image.open(f).convert('RGBA'))[:, :, 3]
    cx, cy, rx, ry = footprint(a)
    s = min(1, 1 / np.hypot(rx / HW, ry / HH))
    rows.append(f"  {os.path.basename(f)[:-4]}:[{cx:.0f},{cy:.0f},{s:.2f}],")

out = os.path.join(ROOT, 'app/scene/treeFit.ts')
with open(out, 'w') as o:
    o.write("// Generated by scripts/fit-trees.py: [footprint centre x, y in the 512 picture, uniform scale].\n")
    o.write("// The footprint centre goes on the plot centre; the scale keeps roots and fallen leaves on the soil.\n")
    o.write("export const TREE_FIT:Record<string,[number,number,number]>={\n" + "\n".join(rows) + "\n};\n")
print(len(rows), 'trees ->', out)
