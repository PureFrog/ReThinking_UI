// the team's books and quizzes (content/master/): a book's text as written (parseBook), its quiz as the team's JSON
// (teamQuiz: mcq with lettered options and correct_id, short_answer; evidence s1.. → section 0..)
export function parseBook(txt:string,source='워런 버핏 주주서한 · 팀 원고'):{title:string;no:number;sections:BookSection[];source:string}{
  const lines=txt.replace(/\r/g,'').split('\n'),head=lines[0].match(/^\[(\d+)권\s*·\s*(.+)\]$/);
  const sections:BookSection[]=[];let para:string[]=[];
  const flush=()=>{if(para.length&&sections.length){sections[sections.length-1].paras.push(para.join(' '));para=[]}};
  for(const l of lines.slice(1)){const t=l.trim(),sec=t.match(/^\d+절\.\s*(.+)$/);
    if(sec){flush();sections.push({title:sec[1],paras:[]});continue}
    if(!t){flush();continue}para.push(t)}
  flush();return {no:head?Number(head[1]):0,title:head?head[2]:lines[0],sections,source}}
type TeamQ={id:string;type:'mcq'|'short_answer';prompt:string;explanation:string;evidence?:{section_id:string}[];options?:{id:string;text:string}[];correct_id?:string;answer?:string};
type TeamQuiz={book_id:string;revision:number;questions:TeamQ[];key_keywords?:{keyword:string;definition:string}[]};
export function teamQuiz(q:TeamQuiz,bookId:string):BookQuiz{
  const sec=(x:TeamQ)=>Math.max(0,Number((x.evidence?.[0]?.section_id??'s1').replace(/\D/g,''))-1);
  return {book_id:bookId,revision:q.revision,keywords:q.key_keywords,questions:q.questions.map(x=>x.type==='mcq'
    ?{kind:'mc',q:x.prompt,options:(x.options??[]).map(o=>o.text) as [string,string,string,string],answer:Math.max(0,(x.options??[]).findIndex(o=>o.id===x.correct_id)),why:x.explanation,sec:sec(x)}
    :{kind:'word',q:x.prompt,answer:x.answer??'',why:x.explanation,sec:sec(x)})}}

